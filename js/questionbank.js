    /**
     * خلط مصفوفة بشكل عشوائي (Fisher-Yates Algorithm)
     * @param {Array} array - المصفوفة المراد خلطها
     * @returns {Array} - مصفوفة جديدة مخلوطة
     */
    function shuffleArray(array) {
        const shuffled = [...array];
        for (let i = shuffled.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
        }
        return shuffled;
    }

    /**
     * خلط خيارات السؤال مع تحديث فهرس الإجابة الصحيحة
     * @param {Object} question - السؤال
     * @returns {Object} - سؤال جديد مع خيارات مخلوطة
     */
    function shuffleQuestionOptions(question) {
        if (!CONFIG.ENABLE_SHUFFLE_OPTIONS) return question;
        
        const correctAnswer = question.options[question.correct];
        const shuffledOptions = shuffleArray(question.options);
        const newCorrectIndex = shuffledOptions.indexOf(correctAnswer);
        
        return {
            ...question,
            options: shuffledOptions,
            correct: newCorrectIndex
        };
    }

    /**
     * تطبيع اسم المادة
     * @param {string} subject - اسم المادة
     * @returns {string} - اسم المادة المطبع
     */
    function normalizeSubject(subject) {
        if (!subject) return '';
        return subject.toLowerCase().trim();
    }

    /**
     * التحقق من صحة اسم المادة
     * @param {string} subject - اسم المادة
     * @returns {boolean}
     */
    function isValidSubject(subject) {
        const normalized = normalizeSubject(subject);
        return Object.values(CONFIG.SUBJECTS).includes(normalized);
    }

