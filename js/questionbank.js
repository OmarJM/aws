    /**
     * الحصول على عدد محدد من الأسئلة العشوائية
     * @param {string} subject - اسم المادة
     * @param {number} count - عدد الأسئلة المطلوبة
     * @param {Object} options - خيارات إضافية
     * @returns {Array} - مصفوفة الأسئلة العشوائية
     */
    function getRandomQuestions(subject, count = 10, options = {}) {
        const {
            lesson = null,
            difficulty = null,
            tag = null,
            shuffleOptions = true
        } = options;
        
        let questions = getAllQuestions(subject);
        
        // تطبيق الفلاتر
        if (lesson) {
            questions = questions.filter(q => q.lesson === lesson);
        }
        if (difficulty) {
            questions = questions.filter(q => q.difficulty === difficulty);
        }
        if (tag) {
            questions = questions.filter(q => q.tags && q.tags.includes(tag));
        }
        
        // خلط الأسئلة
        questions = shuffleArray(questions);
        
        // تحديد العدد
        questions = questions.slice(0, count);
        
        // خلط الخيارات إذا طُلب
        if (shuffleOptions) {
            questions = questions.map(q => shuffleQuestionOptions(q));
        }
        
        debugLog(`Generated ${questions.length} random questions for ${subject}`);
        return questions;
    }

    /**
     * فلترة الأسئلة بمعايير متعددة
     * @param {Object} criteria - معايير الفلترة
     * @returns {Array} - مصفوفة الأسئلة المطابقة
     */
    function filterQuestions(criteria) {
        const {
            subject = null,
            lesson = null,
            difficulty = null,
            tag = null,
            searchTerm = null,
            limit = null
        } = criteria;
        
        let questions = [];
        
        // جمع الأسئلة
        if (subject) {
            questions = getAllQuestions(subject);
        } else {
            // جمع جميع الأسئلة من جميع المواد
            Object.keys(QUESTION_DATA).forEach(subj => {
                const subjQuestions = QUESTION_DATA[subj].map(q => ({ ...q, subject: subj }));
                questions = questions.concat(subjQuestions);
            });
        }
        
        // تطبيق الفلاتر
        if (lesson) {
            questions = questions.filter(q => q.lesson === lesson);
        }
        if (difficulty) {
            questions = questions.filter(q => q.difficulty === difficulty);
        }
        if (tag) {
            questions = questions.filter(q => q.tags && q.tags.includes(tag));
        }
        if (searchTerm) {
            const term = searchTerm.toLowerCase();
            questions = questions.filter(q => 
                q.question.toLowerCase().includes(term) ||
                q.lesson.toLowerCase().includes(term) ||
                (q.explanation && q.explanation.toLowerCase().includes(term))
            );
        }
        
        // تطبيق الحد الأقصى
        if (limit && limit > 0) {
            questions = questions.slice(0, limit);
        }
        
        debugLog(`Filtered questions: ${questions.length} results`);
        return questions;
    }

    /**
     * البحث في بنك الأسئلة
     * @param {string} searchTerm - مصطلح البحث
     * @param {string} subject - اسم المادة (اختياري)
     * @returns {Array} - نتائج البحث
     */
    function searchQuestions(searchTerm, subject = null) {
        if (!searchTerm || searchTerm.trim() === '') {
            return [];
        }
        
        return filterQuestions({
            subject: subject,
            searchTerm: searchTerm
        });
    }

    /**
     * الحصول على إحصائيات بنك الأسئلة
     * @param {string} subject - اسم المادة (اختياري)
     * @returns {Object} - الإحصائيات
     */
    function getStats(subject = null) {
        if (subject) {
            const questions = getAllQuestions(subject);
            const lessons = [...new Set(questions.map(q => q.lesson))];
            const tags = new Set();
            const difficulties = { easy: 0, medium: 0, hard: 0 };
            
            questions.forEach(q => {
                if (q.tags) q.tags.forEach(t => tags.add(t));
                if (q.difficulty) difficulties[q.difficulty]++;
            });
            
            return {
                subject: subject,
                totalQuestions: questions.length,
                totalLessons: lessons.length,
                lessons: lessons,
                totalTags: tags.size,
                tags: Array.from(tags),
                difficulties: difficulties
            };
        }
        
        // إحصائيات عامة لجميع المواد
        const stats = {
            totalSubjects: Object.keys(QUESTION_DATA).length,
            totalQuestions: 0,
            totalLessons: 0,
            subjects: {}
        };
        
        const allLessons = new Set();
        
        Object.keys(QUESTION_DATA).forEach(subj => {
            const questions = QUESTION_DATA[subj];
            stats.totalQuestions += questions.length;
            
            const lessons = [...new Set(questions.map(q => q.lesson))];
            lessons.forEach(l => allLessons.add(l));
            
            stats.subjects[subj] = {
                questions: questions.length,
                lessons: lessons.length
            };
        });
        
        stats.totalLessons = allLessons.size;
        
        return stats;
    }

